#!/usr/bin/env node
// Writes src/lib/commentaryCoverageData.js: which Bible books each commentary in
// the Free Use Bible API (bible.helloao.org) actually covers. Bible Study uses it
// to list only the commentaries that exist for the book you are reading, instead
// of offering ones that would answer "not available".
//
//   node scripts/snapshot-commentary-coverage.mjs
//
// Re-run it when the API adds commentaries or books.
import { writeFileSync } from 'node:fs'

const IDS = [
  'matthew-henry', 'john-calvin', 'john-gill', 'adam-clarke', 'jamieson-fausset-brown', 'keil-delitzsch', 'tyndale',
  'tsk', 'barnes', 'burkitt', 'geneva', 'scofield', 'pnt', 'catena',
]
const out = {}
for (const id of IDS) {
  const res = await fetch(`https://bible.helloao.org/api/c/${id}/books.json`)
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`)
  const { books } = await res.json()
  out[id] = books.map((b) => b.id).join(' ')
  console.log(id.padEnd(24), books.length, 'books')
}
const body = Object.entries(out).map(([id, codes]) => `  '${id}': '${codes}',`).join('\n')
writeFileSync(new URL('../src/lib/commentaryCoverageData.js', import.meta.url), `// Generated by scripts/snapshot-commentary-coverage.mjs -- do not edit by hand.
// Commentary id -> the book codes (the API's USFM-style ids) it covers.
export const COMMENTARY_BOOKS = {
${body}
}
`)
console.log('Wrote src/lib/commentaryCoverageData.js')
